#!/usr/bin/env python3
"""Evaluate the NetHawk model honestly and in detail.

    python3 scripts/evaluate_model.py              # full evaluation
    python3 scripts/evaluate_model.py --cv 5       # add 5-fold cross-validation
    python3 scripts/evaluate_model.py --audit-port # measure Destination Port reliance

Reports class distribution, per-class precision/recall/F1, macro-F1, the
confusion matrix, binary NORMAL-vs-ATTACK metrics, and states plainly whether
the numbers come from real CIC-IDS2017 data or from the synthetic demo data.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np                                                    # noqa: E402
from sklearn.model_selection import StratifiedKFold, cross_val_score  # noqa: E402

from nethawk import config                                            # noqa: E402
from nethawk.datasets.loader import (                                 # noqa: E402
    SOURCE_DEMO, find_cicids_csvs, load_cicids, load_demo, load_training_data,
)
from nethawk.detection.classifier import normalize_label              # noqa: E402
from nethawk.ml import model as ml_model                              # noqa: E402
from nethawk.schema import FEATURE_NAMES, LABEL_COLUMN                # noqa: E402

LINE = "=" * 78


def print_confusion(matrix, labels) -> None:
    width = max(len(l) for l in labels) + 1
    header = " " * (width + 2) + " ".join(f"{l[:7]:>8}" for l in labels)
    print(header)
    for name, row in zip(labels, matrix):
        print(f"  {name:<{width}}" + " ".join(f"{v:>8}" for v in row))


def main() -> int:
    parser = argparse.ArgumentParser(description="Evaluate the NetHawk model")
    parser.add_argument("--demo", action="store_true", help="force the demo dataset")
    parser.add_argument("--data-dir", default=None)
    parser.add_argument("--cv", type=int, default=0,
                        help="run N-fold stratified cross-validation (0 = skip)")
    parser.add_argument("--audit-port", action="store_true",
                        help="retrain without 'Destination Port' to measure reliance on it")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    config.ensure_directories()
    try:
        if args.demo:
            dataset = load_demo()
        elif args.data_dir:
            dataset = load_cicids(Path(args.data_dir))
        else:
            dataset = load_training_data()
    except (FileNotFoundError, ValueError) as exc:
        print(f"[NetHawk] ERROR: {exc}")
        print("[NetHawk] Evaluate the demo dataset instead:  "
              "python3 scripts/evaluate_model.py --demo")
        return 1

    is_demo = dataset.source == SOURCE_DEMO
    print(LINE)
    print("NETHAWK MODEL EVALUATION")
    print(LINE)
    print(f"data source        : {dataset.source}")
    print(f"files              : {', '.join(dataset.files)}")
    print(f"rows after cleaning: {len(dataset.frame)}")
    print(f"duplicates dropped : {dataset.duplicates_removed} (cross-file leakage guard)")
    if is_demo:
        print("\n*** THESE ARE DEMO-DATA RESULTS ***")
        print("The rows are synthetic, generated by src/nethawk/datasets/synthetic.py.")
        print("They measure how well the model separates the demo generator's own")
        print("classes. They are NOT real-world intrusion-detection performance and")
        print("must not be presented as experimental results.")
        print(f"To get real numbers: put CIC-IDS2017 CSVs in {config.CICIDS_DIR}")
        print("and re-run this script. See data/README.md.")
    else:
        print("\nReal CIC-IDS2017 data detected - these are held-out-split results on")
        print("that data. Note the dataset is NOT 802.11-specific (see data/README.md).")

    # ------------------------------------------------------ class balance ---
    y = dataset.frame[LABEL_COLUMN].map(normalize_label)
    print("\n" + LINE)
    print("CLASS DISTRIBUTION (after label normalisation)")
    print(LINE)
    counts = y.value_counts()
    for name, count in counts.items():
        share = 100 * count / len(y)
        bar = "#" * max(1, int(share / 2))
        print(f"  {name:<18} {count:>8}  {share:5.1f}%  {bar}")
    print(f"  imbalance ratio    : {counts.max() / counts.min():.1f}:1 "
          f"(macro-F1 is reported because of this)")

    # ------------------------------------------------------------ training --
    print("\n" + LINE)
    print("HELD-OUT EVALUATION (stratified 75/25 split)")
    print(LINE)
    result = ml_model.train(dataset, seed=args.seed)
    m = result.metrics
    print(f"  train rows : {m['rows_train']}      test rows : {m['rows_test']}")
    if m["dropped_rare_classes"]:
        print(f"  dropped classes with <10 samples: {m['dropped_rare_classes']}")

    report = m["multiclass"]["report"]
    print(f"\n  {'class':<18}{'precision':>10}{'recall':>9}{'f1':>8}{'support':>9}")
    for name in m["classes"]:
        row = report.get(name)
        if row:
            print(f"  {name:<18}{row['precision']:>10.4f}{row['recall']:>9.4f}"
                  f"{row['f1-score']:>8.4f}{int(row['support']):>9}")
    print(f"\n  accuracy           : {m['multiclass']['accuracy']:.4f}")
    print(f"  macro-F1           : {m['multiclass']['macro_f1']:.4f}")
    print(f"  weighted-F1        : {report['weighted avg']['f1-score']:.4f}")

    print("\n  CONFUSION MATRIX (rows = actual, cols = predicted)")
    print_confusion(m["multiclass"]["confusion_matrix"], m["multiclass"]["confusion_labels"])

    b = m["binary"]
    print(f"\n  BINARY NORMAL vs ATTACK")
    print(f"    accuracy         : {b['accuracy']:.4f}")
    print(f"    attack precision : {b['precision_attack']:.4f}")
    print(f"    attack recall    : {b['recall_attack']:.4f}")
    print(f"    attack F1        : {b['f1_attack']:.4f}")

    print("\n  TOP FEATURE IMPORTANCES")
    for item in m["top_features"][:8]:
        bar = "#" * max(1, int(item["importance"] * 120))
        print(f"    {item['feature']:<28}{item['importance']:.4f}  {bar}")

    # --------------------------------------------------- cross-validation ---
    if args.cv:
        print("\n" + LINE)
        print(f"{args.cv}-FOLD STRATIFIED CROSS-VALIDATION (no single-split luck)")
        print(LINE)
        X = dataset.frame[FEATURE_NAMES].astype(float)
        keep = y.value_counts()[lambda s: s >= args.cv].index
        mask = y.isin(keep)
        splitter = StratifiedKFold(n_splits=args.cv, shuffle=True, random_state=args.seed)
        scores = cross_val_score(ml_model.build_model(args.seed), X[mask], y[mask],
                                 cv=splitter, scoring="f1_macro", n_jobs=-1)
        print(f"  macro-F1 per fold : {', '.join(f'{s:.4f}' for s in scores)}")
        print(f"  mean +/- std      : {scores.mean():.4f} +/- {scores.std():.4f}")

    # ------------------------------------------------- port-leakage audit ---
    if args.audit_port:
        print("\n" + LINE)
        print("FEATURE AUDIT: reliance on 'Destination Port'")
        print(LINE)
        print("  In CIC-IDS2017 each attack was run against a specific service, so")
        print("  Destination Port can act as a shortcut that will not generalise to")
        print("  another network. This retrains with that feature zeroed out.")
        reduced = dataset.frame.copy()
        reduced["Destination Port"] = 0.0
        from nethawk.datasets.loader import LoadedDataset
        ablated = ml_model.train(
            LoadedDataset(frame=reduced, source=dataset.source, files=dataset.files),
            seed=args.seed)
        full_f1 = m["multiclass"]["macro_f1"]
        ablated_f1 = ablated.metrics["multiclass"]["macro_f1"]
        print(f"\n  macro-F1 with    Destination Port : {full_f1:.4f}")
        print(f"  macro-F1 without Destination Port : {ablated_f1:.4f}")
        print(f"  drop                              : {full_f1 - ablated_f1:+.4f}")
        if full_f1 - ablated_f1 > 0.05:
            print("  -> the model leans on the port; say so when reporting results.")
        else:
            print("  -> the model does not depend on the port; behaviour features carry it.")

    print("\n" + LINE)
    print(f"Saved metrics: {config.METRICS_PATH}")
    print("Reminder: results above describe "
          + ("SYNTHETIC DEMO DATA." if is_demo else "the loaded CIC-IDS2017 files."))
    print(LINE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
